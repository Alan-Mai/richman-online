// Packs computed lunar years into packages/shared/src/lunar-data.ts (generate.ts writes it).
import { dateOfJdn } from './astronomy';
import { lunarYears, type LunarYear } from './chinese-calendar';

/** The lunar years the table covers; the game's start dates fall in 1998-2010. */
export const LUNAR_DATA_FIRST_YEAR = 1997;
export const LUNAR_DATA_LAST_YEAR = 2199;

/** Julian Day Number of 1 January 1998, day number 0 of the game calendar. */
export const GAME_EPOCH_JDN = 2450815;

const LEAP_SHIFT = 13;
const PER_LINE = 10;

/**
 * One lunar year as an integer: bit i set when month i (counting a leap month in its place) has 30
 * days; bits 13-16 hold the number of the month the leap month follows, 0 for none.
 */
export function packLunarYear(year: LunarYear): number {
  const lengths = year.monthLengths.reduce(
    (bits, days, i) => (days === 30 ? bits | (1 << i) : bits),
    0,
  );
  return lengths | (year.leapMonth << LEAP_SHIFT);
}

/** The TypeScript source of packages/shared/src/lunar-data.ts. */
export function renderLunarData(years: readonly LunarYear[]): string {
  const first = years[0];
  if (first === undefined) throw new Error('no lunar years');
  const packed = years.map(packLunarYear);
  const lines: string[] = [];
  for (let i = 0; i < packed.length; i += PER_LINE) {
    lines.push(`  ${packed.slice(i, i + PER_LINE).join(', ')},`);
  }
  return [
    '// Generated by `pnpm -F extract lunar-gen` (tools/extract/src/lunar/); do not edit.',
    '// Chinese lunar years computed from astronomical formulas, not data from the original game.',
    '',
    `export const LUNAR_FIRST_YEAR = ${dateOfJdn(first.newYearJdn).year};`,
    '',
    '/** Game day number (calendar.ts; 0 = 1 January 1998) of the first day of LUNAR_FIRST_YEAR. */',
    `export const LUNAR_FIRST_NEW_YEAR = ${first.newYearJdn - GAME_EPOCH_JDN};`,
    '',
    '/**',
    ' * One entry per lunar year from LUNAR_FIRST_YEAR: bit i is set when month i (a leap month counted',
    ' * in its place) has 30 days rather than 29; bits 13-16 hold the number of the month the leap',
    ' * month follows, 0 when there is none.',
    ' */',
    'export const LUNAR_YEARS: readonly number[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

export function computeLunarData(): string {
  return renderLunarData(lunarYears(LUNAR_DATA_FIRST_YEAR, LUNAR_DATA_LAST_YEAR));
}
